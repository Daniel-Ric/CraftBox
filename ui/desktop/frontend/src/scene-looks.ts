function scene(
  id: string,
  name: string,
  category: LookCategory,
  description: string,
  tone: Tone,
  settings: Partial<RenderSettings> = {},
  atmosphere: Partial<AtmosphereSettings> = {},
  tags: string[] = [],
  recommended = false,
): SceneLook {
  const combined = {
    quality: "fine" as const,
    grading: true,
    sunLinked: false,
    timeLinked: false,
    ao: 0.45,
    aoRadius: 1.5,
    sharpen: 0.14,
    reflections: 1,
    roughness: 0.85,
    softness: 2.8,
    skyRotation: 0,
    ...tones[tone],
    ...settings,
    atmosphere: { ...atmosphereDefaults, ...atmosphere },
  };
  return {
    id,
    name,
    category,
    description,
    tags,
    recommended,
    settings: combined,
    palette: [
      combined.sky === "night"
        ? "#253b62"
        : combined.sky === "sunset"
          ? "#d7a7ab"
          : combined.sky === "none"
            ? (combined.background ?? "#242b32")
            : "#91bbd3",
      combined.warmth ?? "#fff1dc",
      combined.atmosphere.fogColor,
      category === "nature"
        ? "#69874a"
        : category === "desert"
          ? "#c18d56"
          : category === "winter"
            ? "#dce8ef"
            : "#75878c",
    ],
  };
}
