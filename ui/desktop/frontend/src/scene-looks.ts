function scene(
  id: string,
  name: string,
  category: LookCategory,
  description: string,
  tone: Tone,
  settings: Partial<RenderSettings> = {},
  atmosphere: Partial<AtmosphereSettings> = {},
  tags: string[] = [],
  recommended = false,
): SceneLook {
  const combined = {
    quality: "fine" as const,
    grading: true,
    sunLinked: false,
    timeLinked: false,
    ao: 0.45,
    aoRadius: 1.5,
    sharpen: 0.08,
    waterOpacity: category === "clouds" ? 0.6 : 0.32,
    waterVisibility:
      category === "nature"
        ? 18
        : category === "winter"
          ? 7
          : category === "city"
            ? 8
            : category === "clouds"
              ? 4
              : 12,
    waterRoughness: tone === "night" || tone === "twilight" ? 0.28 : 0.18,
    waterReflections: tone === "night" ? 0.6 : 0.8,
    waterWaves: 0.12,
    waterTint: "#ffffff",
    waterShallowColor:
      category === "winter"
        ? "#568c9c"
        : category === "nature"
          ? "#339a98"
          : "#358f99",
    waterDeepColor:
      tone === "night"
        ? "#10243d"
        : category === "winter"
          ? "#29485e"
          : "#173f59",
    waterColorStrength: 0.65,
    waterColorDepth:
      category === "nature" ? 24 : category === "clouds" ? 8 : 18,
    waterTextureStrength: 0.3,
    waterWaveScale: 1.5,
    waterDeepLight: tone === "night" ? 0.01 : 0.03,
    detailProtection: 0.75,
    reflections: 1,
    roughness: 0.85,
    softness: 2.8,
    skyRotation: 0,
    ...tones[tone],
    ...settings,
    atmosphere: { ...atmosphereDefaults, ...atmosphere },
  };
  return {
    id,
    name,
    category,
    description,
    tags,
    recommended,
    settings: combined,
    palette: [
      combined.sky === "night"
        ? "#253b62"
        : combined.sky === "sunset"
          ? "#d7a7ab"
          : combined.sky === "none"
            ? (combined.background ?? "#242b32")
            : "#91bbd3",
      combined.warmth ?? "#fff1dc",
      combined.atmosphere.fogColor,
      category === "nature"
        ? "#69874a"
        : category === "desert"
          ? "#c18d56"
          : category === "winter"
            ? "#dce8ef"
            : "#75878c",
    ],
  };
}
